#!/usr/bin/env python3
"""EDGE desk state. Added 2026-10-21; history in changelog.md.

Writes STATE.md: one page that says where everything stands, so every chat, scheduled task and automated run starts
from the same picture. Runs at the end of grade.py (after memory.py) and is committed only by the data job
(single-writer rule, like memory/). A Claude session can run it locally to look, then restores the file with
`git checkout -- STATE.md` before committing anything.

STATE.md is generated: never edit it by hand. Decisions, standing rules and open threads go in DESK.md, which
people and Claude sessions write. STATE.md copies DESK.md's open threads so one read covers both.

Reads only: score.json, ledger/picks.json, stats/scan/strategies.json, stats/loop_status.json, ledger/ledger.json
(credits), changelog.md, DESK.md, and the public GitHub API for open pull requests. Every part fails soft.
"""

import json
import re
import urllib.request
from collections import Counter, defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "STATE.md"
REPO = "zrose1999/edgesystem"


def load(path, default):
    try:
        return json.loads(Path(path).read_text())
    except Exception:  # noqa: BLE001
        return default


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def pct(v):
    return "–" if v is None else f"{v * 100:+.1f}%"


def open_prs():
    """Open pull requests: these are waiting on Zack. None when the API cannot be reached."""
    try:
        req = urllib.request.Request(f"https://api.github.com/repos/{REPO}/pulls?state=open&per_page=20",
                                     headers={"User-Agent": "EDGE/1.0", "Accept": "application/vnd.github+json"})
        with urllib.request.urlopen(req, timeout=20) as r:
            return [(p["number"], p["title"], p["created_at"][:10]) for p in json.loads(r.read().decode())]
    except Exception:  # noqa: BLE001
        return None


def desk_section(name):
    """Bullet lines under a '## name' heading in DESK.md."""
    try:
        text = (ROOT / "DESK.md").read_text()
    except OSError:
        return []
    m = re.search(rf"^## {re.escape(name)}\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return [ln for ln in (m.group(1).splitlines() if m else []) if ln.startswith("- ")]


def recent_changes(days=7, now=None):
    out = []
    try:
        lines = (ROOT / "changelog.md").read_text().splitlines()
    except OSError:
        return out
    floor = (now - timedelta(days=days)).strftime("%Y-%m-%d")
    for ln in lines:
        m = re.match(r"- (\d{4}-\d{2}-\d{2}): (.*)", ln)
        if not m or m.group(1) < floor:
            continue
        first = re.split(r"(?<=[.)])\s", m.group(2), maxsplit=1)[0]
        out.append(f"- {m.group(1)}: {first[:160]}")
    return out[:15]


def build():
    now_dt = datetime.now(timezone.utc)
    now = iso(now_dt)
    week = iso(now_dt - timedelta(days=7))
    score = load(ROOT / "score.json", {})
    picks = load(ROOT / "ledger" / "picks.json", {"picks": []}).get("picks") or []
    scan = load(ROOT / "stats" / "scan" / "strategies.json", {"strategies": {}})
    loop = load(ROOT / "stats" / "loop_status.json", {})
    credits = (load(ROOT / "ledger" / "ledger.json", {}).get("credits") or {}).get("remaining")

    status = {p["id"]: p for p in score.get("patterns") or []}
    by_pat = score.get("byPattern") or {}
    week_reads, upcoming, rereads, sports, first, last = Counter(), Counter(), Counter(), defaultdict(set), {}, {}
    for p in picks:
        pat = p.get("pattern")
        if not pat:
            continue
        t = p.get("pickedAt") or ""
        first[pat] = min(first.get(pat, "9"), t or "9")
        last[pat] = max(last.get(pat, ""), t)
        sports[pat].add(p.get("sport"))
        if t >= week:
            if p.get("kind") == "reread":
                rereads[pat] += 1
            else:
                week_reads[pat] += 1
        if p.get("kind") in ("pick", "lean") and (p.get("commence") or "") > now:
            upcoming[pat] += 1

    L = [f"# EDGE state ({now})", "",
         "Generated by state.py after every grade run. Do not edit; decisions and open threads go in DESK.md.",
         "Read this and DESK.md before doing anything in a chat, scheduled task or review.", ""]

    L.append("## Waiting on Zack")
    prs = open_prs()
    if prs is None:
        L.append("- (GitHub API not reachable this run; check open pull requests by hand)")
    elif not prs:
        L.append("- No open pull requests.")
    else:
        L += [f"- PR #{n}: {t} (opened {d})" for n, t, d in prs]
    L.append("")

    L.append("## Open threads (copied from DESK.md)")
    L += desk_section("Open threads") or ["- none listed"]
    L.append("")

    L.append("## Strategies taking reads")
    L.append("Reads 7d = picks, leans and passes stamped in the last 7 days (repeat reads shown in brackets, never counted). "
             "Upcoming = picks and leans on games not yet started, whenever stamped. Graded and CLV = one test per "
             "pattern, row and side (grade.py byPattern). Status from grade.py.")
    L.append("")
    L.append("| Pattern | Sports | Status | First read | Last read | Reads 7d | Upcoming | Graded | Mean CLV | t |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    names = sorted(set(week_reads) | set(upcoming) | set(rereads), key=lambda k: (-upcoming[k], -week_reads[k], k))
    for k in names:
        bp, st = by_pat.get(k) or {}, (status.get(k) or {}).get("status", "shadow")
        L.append(f"| {k} | {', '.join(sorted(s for s in sports[k] if s))} | {st} | {first[k][:10]} | {last[k][:10]} | {week_reads[k]}{f' (+{rereads[k]})' if rereads[k] else ''} | "
                 f"{upcoming[k]} | {bp.get('graded', 0)} | {pct(bp.get('meanClvProb'))} | {bp.get('tStat', '–')} |")
    quiet = sorted(k for k in status if k not in names)
    if quiet:
        L.append("")
        L.append("No reads in 7 days: " + ", ".join(quiet) + ".")
    L.append("")

    S = scan.get("strategies") or {}
    tracking = [s for s in S.values() if s.get("status") == "tracking"]
    L.append("## Scanner (scan.py)")
    if not S:
        L.append("- No scanner registry yet (stats/scan/strategies.json). First run lands with the 11:07Z morning job.")
    else:
        stamped = sum(week_reads[s["id"]] for s in tracking if s.get("id") in week_reads)
        L.append(f"- Last scan {scan.get('asOf', '?')}: {scan.get('tests', '?')} tests, {scan.get('survivors', '?')} survivors, "
                 f"{len(tracking)} tracking, {sum(1 for s in S.values() if s.get('status') == 'lapsed')} lapsed. "
                 f"Scanner reads in the last 7 days: {stamped}.")
        for s in sorted(tracking, key=lambda s: -s.get("score", 0))[:5]:
            L.append(f"  - {s['id']} (score {s.get('score')}, found {str(s.get('firstFound', ''))[:10]})")
    L.append("")

    L.append("## North-star checks (2026-10-21)")
    bm = score.get("benchmark") or {}
    if bm:
        L.append(f"- Score benchmark: Pinnacle close on {bm.get('onPinnacle', 0)} counted reads, print close on "
                 f"{bm.get('onPrint', 0)}. Mean CLV print {pct((bm.get('print') or {}).get('mean'))}, Pinnacle "
                 f"{pct((bm.get('pinnacle') or {}).get('mean'))}, at the best US price "
                 f"{pct((bm.get('bestPrice') or {}).get('mean'))} (n {(bm.get('bestPrice') or {}).get('n', 0)}).")
    conf = [p for p in score.get("patterns") or [] if p.get("status") == "confirming"]
    L.append("- Confirming (cleared the bar, need fresh picks): " + (", ".join(
        f"{p['id']} {((p.get('confirmation') or {}).get('freshNow') or 0)}/{(p.get('confirmation') or {}).get('needed')}"
        for p in conf) if conf else "none") + ".")
    mc = load(ROOT / "stats" / "modelcheck.json", {})
    pats = sorted((mc.get("patterns") or {}).values(), key=lambda v: -v.get("tRealized", 0))
    if pats:
        top = ", ".join(f"{v['pattern']} realized {v['meanRealized']:+g} {v['unit']} vs predicted "
                        f"{v['meanPredicted']:+g} (n {v['n']}, t {v['tRealized']})" for v in pats[:3])
        L.append(f"- Move check, strongest: {top}. Proven (feeding edge-stack): "
                 + (", ".join(mc.get("proven") or []) or "none yet") + ".")
    mk = (load(ROOT / "trading" / "ledger.json", {}).get("status") or {}).get("maker")
    if mk:
        L.append(f"- Kalshi maker paper book: {mk.get('orders')} orders, fill rate {mk.get('fillRate')}, net CLV "
                 f"{pct(mk.get('meanClvNet'))} on {mk.get('clvN')}; paired with taker on {mk.get('pairedWithTaker')}: "
                 f"maker {pct(mk.get('pairedMakerClvNet'))} vs taker {pct(mk.get('pairedTakerClvNet'))} (net of fees).")
    L.append("")

    L.append("## Pipeline")
    sp = loop.get("sports") or {}
    bad = {k: v.get("status") for k, v in sp.items() if v.get("status") not in ("ok", "quiet")}
    L.append(f"- Loop status {loop.get('asOf', '?')}: " + (", ".join(f"{k} {v}" for k, v in bad.items()) if bad
                                                          else f"all {len(sp)} sports ok or quiet") + ".")
    L.append(f"- Odds API credits remaining: {credits if credits is not None else 'unknown'}.")
    L.append(f"- Graded picks {score.get('graded', '?')} of {score.get('picks', '?')} (reads logged {score.get('reads', '?')}); overall mean CLV "
             f"{pct(score.get('meanClvProb'))}; official record {score.get('officialRecord', '?')}.")
    L.append("- Rolling feature summary: memory/summary.md. Leads: memory/hypotheses.md.")
    L.append("")

    L.append("## Changes in the last 7 days (changelog.md, first sentence)")
    L += recent_changes(7, now_dt) or ["- none"]
    L.append("")

    OUT.write_text("\n".join(L) + "\n")
    return {"state": str(OUT.name), "strategies": len(names), "openPRs": None if prs is None else len(prs)}


if __name__ == "__main__":
    print(json.dumps(build()))
